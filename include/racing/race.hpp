// A race: N cars, T teams, one circuit, and everything that happens between
// them.
//
// This is the environment a policy sees. One `RaceEnv` is one race; `VecRaceEnv`
// runs many of them side by side, which is the only way the throughput works --
// a policy step costs far less than a Python round trip, so what matters is how
// many races advance per call rather than how fast one of them runs.
//
// Every car in a race is an agent. They share an action space and, in the
// reference training loop, a policy; what separates them is which team they are
// on, and therefore whose result their reward depends on. See
// RewardConfig::team_weight, which is the dial that decides whether the field
// behaves like eight individuals or four teams of two.

#pragma once

#include <cstdint>
